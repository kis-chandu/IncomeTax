import re, os, json

BASE = "/home/user/IncomeTax/FY2024-25_AY2025-26/05-Bank-Statements"
AMT = r"-?\d+(?:,\d+)*\.\d{2}"
DT_SL = r"\d{2}/\d{2}/\d{4}"
DT_DS = r"\d{2}-[A-Za-z]{3}-\d{4}"
DT_KT = r"\d{2}\s[A-Za-z]{3}\s\d{4}"
def tofloat(s): return float(s.replace(",", ""))

# ---------- HDFC ----------
HDFC_SKIP = re.compile(r"(Generation Date|Requesting Branch|Generated by|HDFC BANK|"
    r"\*Closing Balance|Contents of this|State account branch|GSTIN|Registered Office|"
    r"Page\s+\d+\s+of\s+\d+|Statement From|Account Branch|A/C Open Date|Joint Account|Cust ID|"
    r"Account Status|Account number|RTGS/NEFT|JOINT HOLDERS|Nomination|MICR|Expected AMB|"
    r"OD Limit|PRIME POTENTIAL|Phone No\.|Account Open Regular|Not Applicable|"
    r"18002600|HDFC0000010|gorai\.chandrakant|Kala Chand Gorai|Mukunda, Brundhavan|"
    r"Kurudu Sonnenahalli|Bengaluru|Karnataka|India$|560067|Besant Nagar|7th Avenue|"
    r"Mg Road|Tamil Nadu|Chennai 600|^:\s|^\s*(Limit|State|City|Address|Email|Currency|"
    r"Pr\.Code|Br\.Code|MR\.)\b|^\s*\d{6,9}\s*$|^\s*0\.00\s*$)", re.I)

def parse_hdfc(path):
    txns = []
    term = re.compile(rf"({DT_SL})\s+({AMT})\s+({AMT})\s+({AMT})\s*$")
    bare = re.compile(rf"^\s*({DT_SL})\s*$")
    start = re.compile(rf"^\s*({DT_SL})\s+(.+)$")
    for p in PdfReader(path).pages:
        buf = []
        for raw in (p.extract_text() or "").splitlines():
            l = raw.rstrip()
            m = term.search(l)
            if not m and HDFC_SKIP.search(l):
                continue
            buf.append(l)
            if m:
                vd, wd, dep, bal = m.groups()
                posted = vd; head = []
                for bl in buf[:-1]:
                    bm = bare.match(bl) or start.match(bl)
                    if bm:
                        posted = bm.group(1)
                        rem = bl[bm.end(1):].strip() if start.match(bl) else ""
                        if rem: head.append(rem)
                    elif bl.strip():
                        head.append(bl.strip())
                narr = " ".join(head + [l[:m.start()].strip()])
                narr = re.sub(r"^.*Chandrakant Gorai\s*", "", narr).strip()  # strip page-header name bleed
                narr = re.sub(rf"^{DT_SL}\s*", "", narr).strip()
                narr = re.sub(r"\s+[A-Z0-9@./\-]{6,}\s*$", "", narr).strip()  # drop tail ref-id
                txns.append((posted, narr, tofloat(wd), tofloat(dep), tofloat(bal)))
                buf = []
    return txns

# ---------- SBI ----------
SBI_STRIP = [
    (r"Relationship Summary.*?STATEMENT OF ACCOUNT\s*\n?\s*State Bank of India", ""),
    (r"Account Summary.*?Statement From : 01-04-2024 to 31-03-2025", ""),
    (r"Branch Name : DODDA", ""),
    (r"Please do not share.*?signature\.", ""),
    (r"Statement Summary : .*", ""),
]
def parse_sbi(path):
    txns = []
    start = re.compile(rf"^\s*({DT_SL})\s+({DT_SL})\s*(.*)$")
    cr = re.compile(rf"(.*?)-\s+-\s+({AMT})\s+({AMT})\s*$")
    dr = re.compile(rf"(.*?)-\s+({AMT})\s+-\s+({AMT})\s*$")
    cur = None
    def flush():
        nonlocal cur
        if cur:
            narr = " ".join(cur[1]).strip()
            wd = cur[2] or 0.0; dep = cur[3] or 0.0
            if cur[4] is not None:
                txns.append((cur[0], narr, wd, dep, cur[4]))
        cur = None
    for p in PdfReader(path).pages:
        text = p.extract_text() or ""
        for pat, rep in SBI_STRIP:
            text = re.sub(pat, rep, text, flags=re.S)
        for raw in text.splitlines():
            l = raw.rstrip()
            if not l.strip() or re.search(r"Page no\.|^\s*Balance\s*$", l):
                continue
            ms = start.match(l)
            if ms:
                flush()
                cur = [ms.group(1), [ms.group(3)], 0.0, 0.0, None]
                rest = ms.group(3)
            elif cur is not None:
                rest = l
            else:
                continue
            # single-line terminator: "- - x y" (credit) or "- x - y" (debit) at end
            mc = re.search(rf"-\s+-\s+({AMT})\s+({AMT})\s*$", rest)
            mdr = (not mc) and re.search(rf"-\s+({AMT})\s+-\s+({AMT})\s*$", rest)
            if mc:
                cur[3], cur[4] = tofloat(mc.group(1)), tofloat(mc.group(2))
                cur[1][-1] = re.sub(rf"-\s+-\s+{AMT}\s+{AMT}\s*$", "", cur[1][-1]).strip()
                flush()
            elif mdr:
                cur[2], cur[4] = tofloat(mdr.group(1)), tofloat(mdr.group(2))
                cur[1][-1] = re.sub(rf"-\s+{AMT}\s+-\s+{AMT}\s*$", "", cur[1][-1]).strip()
                flush()
            elif cur is not None:
                cur[1].append(rest.strip())
    flush()
    return txns

# ---------- IDFC (region-strip per page; DD-MMM-YYYY; amount+balance 2-col) ----------
def parse_idfc(path):
    txns = []
    start = re.compile(rf"^\s*({DT_DS})\s+({DT_DS})\s*(.*)$")
    stated = None
    cur = None
    for p in PdfReader(path).pages:
        text = p.extract_text() or ""
        m = re.search(r"Opening Balance Total Debit Total Credit Closing Balance\s+"
                      rf"({AMT})\s+({AMT})\s+({AMT})\s+({AMT})", text.replace("\n", " ").replace("6, ","6,"))
        if m and stated is None:
            g = tuple(map(tofloat, m.groups()))
            stated = (g[0], g[2], g[1], g[3])  # normalize to (opening, credit, debit, closing)
        text = re.sub(r"STATEMENT OF ACCOUNT.*?No Debit Credit Balance", "", text, flags=re.S)
        text = re.sub(r"REGISTERED OFFICE.*?Page\s+\d+\s+of\s+\d+", "", text, flags=re.S)
        for raw in text.splitlines():
            l = raw.strip()
            if not l: continue
            ms = start.match(l)
            if ms:
                if cur: _flush2(cur, txns)
                cur = [ms.group(1), [ms.group(3)]]
            elif cur is not None:
                cur[1].append(l)
    if cur: _flush2(cur, txns)
    out, prev = [], stated[0] if stated else None
    for dt, narr, amt, bal in txns:
        if prev is not None:
            wd, dep = (0.0, amt) if bal >= prev else (amt, 0.0)
        else:
            wd, dep = 0.0, amt
        out.append((dt, narr, wd, dep, bal)); prev = bal
    return out, stated

def _flush2(cur, txns):
    narr = " ".join(cur[1]).strip()
    mm = re.search(rf"({AMT})\s+({AMT})\s*$", narr)
    if not mm: return
    amt, bal = tofloat(mm.group(1)), tofloat(mm.group(2))
    narr = narr[:mm.start()].strip()
    txns.append((cur[0], narr, amt, bal))

# ---------- Kotak ----------
def parse_kotak(path):
    txns = []
    start = re.compile(rf"^\s*(\d+)\s+({DT_KT})\s+(.*)$")
    opening = None
    cur = None
    for pi, p in enumerate(PdfReader(path).pages):
        text = p.extract_text() or ""
        if pi == 0:
            mo = re.search(rf"Opening Balance - - - ({AMT})", text.replace("\n", " "))
            if mo: opening = tofloat(mo.group(1))
        text = re.sub(r"Account Statement.*?Deposit \(Cr\.\) Balance", "", text, flags=re.S)
        text = re.sub(r"- - Opening Balance - - - " + AMT, "", text)
        for raw in text.splitlines():
            l = raw.rstrip()
            if not l.strip(): continue
            ms = start.match(l)
            if ms:
                if cur: _flush2(cur, txns)
                cur = [ms.group(2), [ms.group(3)]]
            elif cur is not None:
                cur[1].append(l.strip())
    if cur: _flush2(cur, txns)
    out, prev = [], opening
    for dt, narr, amt, bal in txns:
        if prev is not None:
            wd, dep = (0.0, amt) if bal >= prev else (amt, 0.0)
        else:
            wd, dep = 0.0, amt
        out.append((dt, narr, wd, dep, bal)); prev = bal
    return out, opening

# ---------- Jio (3-amount lines; region-strip) ----------
def parse_jio(path):
    txns = []
    start = re.compile(rf"^\s*({DT_DS})\s+({DT_DS})\s*(.*)$")
    cur = None
    for p in PdfReader(path).pages:
        text = p.extract_text() or ""
        text = re.sub(r"Jio Payments Bank Limited.*?Page\s+\d+\s+of\s+\d+", "", text, flags=re.S)
        text = re.sub(r"Account Statement.*?CLOSING\s*\n?\s*BALANCE", "", text, count=1, flags=re.S)
        text = re.sub(r"REACH US AT:.*?CLOSING\s*\n?\s*BALANCE", "", text, flags=re.S)
        text = re.sub(r"TRANSACTION\s*\n?\s*DATE\s*\n?\s*VALUE\s*\n?\s*DATE", "", text)
        for raw in text.splitlines():
            l = raw.rstrip()
            if not l.strip(): continue
            ms = start.match(l)
            if ms:
                if cur: _flush3(cur, txns)
                cur = [ms.group(1), [ms.group(3)]]
            elif cur is not None:
                cur[1].append(l.strip())
    if cur: _flush3(cur, txns)
    return txns

def _flush3(cur, txns):
    narr = " ".join(cur[1]).strip()
    mm = re.search(rf"({AMT})\s+({AMT})\s+({AMT})\s*$", narr)
    if not mm: return
    wd, dep, bal = map(tofloat, mm.groups())
    narr = narr[:mm.start()].strip()
    txns.append((cur[0], narr, wd, dep, bal))

